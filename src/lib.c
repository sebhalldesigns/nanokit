int nk_run(nk_run_info_t *info, int argc, char **argv)
{
    printf("Hello world!\n");

    if (!backend_init())
    {
        fprintf(stderr, "Failed to initialize backend.\n");
        return -1;
    }

    info->launch_callback();

    backend_run();

    return 0;
}

